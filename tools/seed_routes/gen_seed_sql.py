"""Generate sql/seed_curated.sql (idempotent) from final/*.json — the only write path for curated routes.
Runs as the project DB owner via `supabase db query --linked -f`; no service key involved."""
import json, uuid, glob, os
from routes import SPECS
NS = uuid.UUID("6f1c2a52-1d3b-4a0e-9a57-2c0f5f7e9c11")
AUTHOR = uuid.uuid5(NS, "nomad-curated-author")
CDN = "https://smdnbjvelqsgjoubognc.supabase.co/storage/v1/object/public/route-covers/curated/"

def q(s):
    if s is None: return "null"
    tag = "nm"
    while f"${tag}$" in s: tag += "x"
    return f"${tag}${s}${tag}$"
def num(x): return "null" if x is None else repr(float(x)) if isinstance(x, float) else str(x)

out = ["-- Nomad Curated launch routes. Generated by tools/seed_routes/gen_seed_sql.py — idempotent (safe to re-run).",
       "-- Geometry © OpenStreetMap contributors (ODbL); elevation from a DEM; see tools/seed_routes/sources.json.",
       "begin;",
       f"""insert into auth.users (instance_id, id, aud, role, email, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, is_anonymous)
values ('00000000-0000-0000-0000-000000000000', '{AUTHOR}', 'authenticated', 'authenticated', 'curated@nomadterminal.invalid', now(),
        '{{"provider":"email","providers":["email"]}}', '{{"username":"nomad_curated","display_name":"Nomad Curated"}}', now(), now(), false)
on conflict (id) do nothing;""",
       f"update public.profiles set home_location = 'Worldwide' where id = '{AUTHOR}' and home_location is null;"]
for sp in SPECS:
    slug = sp["slug"]; d = json.load(open(f"final/{slug}.json")); r = d["route"]
    rid = uuid.uuid5(NS, "route:" + slug)
    cover = (CDN + slug + ".jpg") if d.get("cover") else None
    prof = "ARRAY[" + ",".join(str(x) for x in r["elevation_profile"]) + "]::numeric[]"
    out.append(f"-- {slug}")
    out.append(f"""insert into public.routes (id, author_id, title, place, cover_image_url, difficulty, transport, transport_label, distance_km, coordinates, season, duration,
  ascent_m, high_point_m, elevation_profile, elevation_peak_label, quote, quote_author, visibility, status, track_points)
values ('{rid}', '{AUTHOR}', {q(r["title"])}, {q(r["place"])}, {q(cover)}, '{r["difficulty"]}', '{r["transport"]}', {q(r["transport_label"])}, {r["distance_km"]}, {q(r["coordinates"])}, {q(r["season"])}, {q(r["duration"])},
  {r["ascent_m"]}, {r["high_point_m"]}, {prof}, {q(r["elevation_peak_label"])}, {q(r["description"])}, '— NOMAD CURATED', 'public', 'published', {q(json.dumps(r["track_points"]))}::jsonb)
on conflict (id) do nothing;""")
    out.append(f"delete from public.route_segments where route_id = '{rid}';")
    for i, s in enumerate(d["segments"]):
        out.append(f"insert into public.route_segments (route_id, icon, name, distance_km, tint, sort_order) values ('{rid}', {q(s['icon'])}, {q(s['name'])}, {s['distance_km']}, {q(s['tint'])}, {i});")
    out.append(f"delete from public.route_requirements where route_id = '{rid}';")
    for i, s in enumerate(d["requirements"]):
        out.append(f"insert into public.route_requirements (route_id, icon, title, subtitle, tint, sort_order) values ('{rid}', {q(s['icon'])}, {q(s['title'])}, {q(s['subtitle'])}, {q(s['tint'])}, {i});")
    out.append(f"delete from public.route_points_of_interest where route_id = '{rid}';")
    for i, p in enumerate(d["pois"]):
        out.append(f"insert into public.route_points_of_interest (route_id, lat, lng, category, title, note, sort_order) values ('{rid}', {p['lat']}, {p['lng']}, {q(p['category'])}, {q(p['title'])}, {q(p['note'])}, {i});")
out.append("commit;")
out.append("select title, place, difficulty, distance_km, status from public.routes where author_id = '" + str(AUTHOR) + "' order by created_at;")
open("sql/seed_curated.sql", "w").write("\n".join(out) + "\n")
print(len(out), "statements ->", "sql/seed_curated.sql", os.path.getsize("sql/seed_curated.sql")//1024, "KB; author", AUTHOR)
